#!/usr/bin/env node
// Summarize every <suite>/results/compare.json into RESULTS.md: per-suite and total
// input tokens and dollar cost, direct vs through the gateway, plus answer quality and
// the gateway's latency overhead. Numbers only come from the committed result files.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { loadConfig, suiteNames } from './lib/loadConfig.mjs';
import { savedPct } from './lib/cost.mjs';

const fmtInt = (n) => (n == null ? '—' : Math.round(n).toLocaleString('en-US'));
const fmtUsd = (n) => (n == null ? '—' : `$${n.toFixed(4)}`);
const fmtPct = (n) => (n == null ? '—' : `${n}%`);
const median = (xs) => {
  const s = xs.filter((x) => x != null).sort((a, b) => a - b);
  if (!s.length) return null;
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};

/** Totals over rows that completed; cost sums only when every row is priced. */
export function totals(rows) {
  const ok = rows.filter((r) => !r.error);
  const sum = (f) => ok.reduce((a, r) => a + (f(r) ?? 0), 0);
  const priced = ok.length > 0 && ok.every((r) => r.direct.costUsd != null && r.gateway.costUsd != null);
  const t = {
    n: ok.length,
    errors: rows.length - ok.length,
    directInput: sum((r) => r.direct.input),
    gatewayInput: sum((r) => r.gateway.input),
    directCost: priced ? sum((r) => r.direct.costUsd) : null,
    gatewayCost: priced ? sum((r) => r.gateway.costUsd) : null,
    medianOverheadMs: median(ok.map((r) => r.latencyOverheadMs)),
    quality: { PASS: 0, MARGINAL: 0, FAIL: 0 },
  };
  for (const r of ok) if (r.quality) t.quality[r.quality]++;
  t.inputSavedPct = savedPct(t.directInput, t.gatewayInput);
  t.costSavedPct = savedPct(t.directCost, t.gatewayCost);
  return t;
}

export function renderResults(cfg) {
  const meta = existsSync(join(cfg.root, 'results', 'run-meta.json'))
    ? JSON.parse(readFileSync(join(cfg.root, 'results', 'run-meta.json'), 'utf8'))
    : {};
  const bySuite = suiteNames(cfg).map((s) => {
    const f = join(cfg.root, s, 'results', 'compare.json');
    return { suite: s, rows: existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : [] };
  });
  const all = totals(bySuite.flatMap((b) => b.rows));
  const q = (t) => `${t.quality.PASS} / ${t.quality.MARGINAL} / ${t.quality.FAIL}`;

  let md = `# Results — direct vs through Anyray\n\n`;
  md += `Generated by \`npm run report\` from \`<suite>/results/compare.json\`. Do not hand-edit.\n\n`;
  md += `- Model: \`${meta.model ?? '?'}\` · judge: \`${meta.judgeModel ?? 'none'}\`\n`;
  md += `- Gateway: \`${meta.gatewayUrl ?? '?'}\` · direct: \`${meta.directUrl ?? '?'}\`\n`;
  md += `- Last run started: ${meta.timestamp ?? '?'} · call order: ${meta.order ?? '?'}\n\n`;
  md += `## By suite\n\n`;
  md += `| Suite | Workloads | Direct input (tok) | Gateway input (tok) | Input saved | Direct cost | Gateway cost | Cost saved | Quality P / M / F | Median overhead |\n`;
  md += `|---|--:|--:|--:|--:|--:|--:|--:|:-:|--:|\n`;
  for (const { suite, rows } of bySuite) {
    const t = totals(rows);
    md += `| [\`${suite}/\`](${suite}/) | ${t.n}${t.errors ? ` (+${t.errors} err)` : ''} | ${fmtInt(t.directInput)} | ${fmtInt(t.gatewayInput)} | ${fmtPct(t.inputSavedPct)} | ${fmtUsd(t.directCost)} | ${fmtUsd(t.gatewayCost)} | **${fmtPct(t.costSavedPct)}** | ${q(t)} | ${fmtInt(t.medianOverheadMs)} ms |\n`;
  }
  md += `| **Total** | **${all.n}** | **${fmtInt(all.directInput)}** | **${fmtInt(all.gatewayInput)}** | **${fmtPct(all.inputSavedPct)}** | **${fmtUsd(all.directCost)}** | **${fmtUsd(all.gatewayCost)}** | **${fmtPct(all.costSavedPct)}** | **${q(all)}** | **${fmtInt(all.medianOverheadMs)} ms** |\n\n`;

  const skipped = bySuite.flatMap(({ suite }) =>
    (cfg.suites[suite].workloads ?? []).filter((w) => w.skip).map((w) => ({ suite, ...w }))
  );
  if (skipped.length) {
    md += `Not run (${skipped.length}):\n\n`;
    for (const w of skipped) md += `- \`${w.suite}/${w.id}\`: ${w.skip}\n`;
    md += `\n`;
  }

  md += `## By workload\n\n`;
  md += `| Workload | Input direct → gateway | Input saved | Cost saved | Quality (score) | Overhead |\n`;
  md += `|---|--:|--:|--:|:-:|--:|\n`;
  for (const { suite, rows } of bySuite) {
    for (const r of rows) {
      if (r.error) {
        md += `| \`${suite}/${r.id}\` | error: ${r.error.replace(/\|/g, '\\|').slice(0, 80)} | | | | |\n`;
        continue;
      }
      const score = r.judge ? ` (${r.judge.score})` : '';
      md += `| \`${suite}/${r.id}\` | ${fmtInt(r.direct.input)} → ${fmtInt(r.gateway.input)} | ${fmtPct(r.inputSavedPct)} | ${fmtPct(r.costSavedPct)} | ${r.quality ?? '—'}${score} | ${fmtInt(r.latencyOverheadMs)} ms |\n`;
    }
  }
  return { md, all };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const cfg = loadConfig();
  const { md, all } = renderResults(cfg);
  writeFileSync(join(cfg.root, 'RESULTS.md'), md);
  console.log(`Wrote RESULTS.md — ${all.n} workloads, input ${fmtPct(all.inputSavedPct)}, cost ${fmtPct(all.costSavedPct)}`);
}
